@register.simple_tag(takes_context=True)
def t(context, key):
    request = context.get('request')
    language = getattr(request, 'LANGUAGE_CODE', settings.LANGUAGE_CODE)[:2]
    return TEXT.get(language, TEXT['fr']).get(key, key)


@register.simple_tag(takes_context=True)
def field_label(context, field_name, default_label):
    request = context.get('request')
    language = getattr(request, 'LANGUAGE_CODE', settings.LANGUAGE_CODE)[:2]
    key = f'field_{field_name}'
    return TEXT.get(language, TEXT['fr']).get(key, default_label)


@register.simple_tag(takes_context=True)
def display_choice(context, label):
    request = context.get('request')
    language = getattr(request, 'LANGUAGE_CODE', settings.LANGUAGE_CODE)[:2]
    return CHOICES.get(label, label) if language == 'en' else label


@register.simple_tag(takes_context=True)
def render_field(context, field):
    request = context.get('request')
    language = getattr(request, 'LANGUAGE_CODE', settings.LANGUAGE_CODE)[:2]
    widget = field.field.widget
    if language == 'en' and hasattr(widget, 'choices'):
        import copy

        widget = copy.copy(widget)
        widget.choices = [
            (value, CHOICES.get(str(label), label))
            for value, label in widget.choices
        ]
    return field.as_widget(widget=widget)
